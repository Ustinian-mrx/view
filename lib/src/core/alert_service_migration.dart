// 语音播报服务迁移指南
//
// 优化前后对比：
//
// 1. 多目标支持
//    - 优化前：只播报优先级最高的一个目标
//    - 优化后：智能合并多个目标，播报最关键信息
//
// 2. 动态间隔
//    - 优化前：固定间隔（如1.2秒）
//    - 优化后：根据风险等级动态调整（危险0.72秒，安全2.4秒）
//
// 3. 智能抑制
//    - 优化前：相同消息在间隔内不重复
//    - 优化后：连续相同消息时，间隔逐次翻倍
//
// 4. 方向感知
//    - 优化前：简单左/中/右
//    - 优化后：考虑目标垂直位置，区分近处/远处
//
// 5. 距离表达
//    - 优化前：固定格式"约1.6米"
//    - 优化后：分层表达（厘米/米/较远）
//
// 6. 场景感知
//    - 优化前：无
//    - 优化后：追踪红绿灯状态，优先播报
//
// 迁移步骤：
//
// 1. 在 home_page.dart 中替换 AlertService 为 AlertServiceV2
//
//    旧代码：
//    final _alerts = AlertService();
//
//    新代码：
//    final _alerts = AlertServiceV2();
//
// 2. 在 settings_page.dart 中替换 AlertService 为 AlertServiceV2
//
//    旧代码：
//    final _alerts = AlertService();
//
//    新代码：
//    final _alerts = AlertServiceV2();
//
// 3. 其他使用 AlertService 的地方也需要替换
//
// 注意事项：
//
// - 优化后的播报内容更长，可能需要调整播报间隔
// - 动态间隔可能导致某些场景下播报过于频繁或稀疏
// - 建议在真机上测试不同场景下的播报效果
